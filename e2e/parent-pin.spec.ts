import { expect, test } from '@playwright/test'

test('家长 PIN：手机与桌面可输入；错误 PIN 留在登录页，正确 PIN 直接进入家长端', async ({ page }) => {
  await page.goto('/login')
  await page.getByRole('button', { name: '输入家庭码加入', exact: true }).click()
  await page.getByLabel('家庭码', { exact: true }).fill('123456')
  const pin = page.getByLabel('家长 PIN', { exact: true })
  await expect(pin).toHaveAttribute('type', 'password')
  await expect(page.getByRole('button', { name: '进入桃阅读', exact: true })).toBeDisabled()
  for (const width of [320, 390, 1024]) {
    await page.setViewportSize({ width, height: 844 })
    await expect(pin).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  }
  await page.setViewportSize({ width: 390, height: 844 })
  await pin.fill('000000')
  await page.getByRole('button', { name: '进入桃阅读', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('家长 PIN 不正确')
  await expect(page).toHaveURL(/\/login/)
  await page.screenshot({ path: 'output/playwright/adversarial-20261015/10-parent-pin-login.png', fullPage: true })
  await pin.fill('864209')
  await pin.press('Enter')
  await expect(page).toHaveURL(/\/parent/)
  await expect(page.getByRole('heading', { name: '桃阅读 · 家长端', exact: true })).toBeVisible()
})

test('创建家庭与更改 PIN：确认不一致不可提交，更新后旧家长退出而孩子不受影响', async ({ page, request }) => {
  await page.goto('/login')
  await page.getByRole('button', { name: /创建新家庭/ }).click()
  await page.getByLabel('设置家长 PIN', { exact: true }).fill('730862')
  await page.getByLabel('再次输入家长 PIN', { exact: true }).fill('730861')
  await page.getByRole('checkbox').check()
  await expect(page.getByRole('button', { name: '创建我的家庭', exact: true })).toBeDisabled()
  await page.getByLabel('再次输入家长 PIN', { exact: true }).fill('730862')
  await page.getByRole('button', { name: '创建我的家庭', exact: true }).click()
  const familyCode = (await page.getByTestId('family-code').innerText()).trim()
  await page.getByRole('button', { name: '进入家长端', exact: true }).click()
  await expect(page).toHaveURL(/\/parent/)
  const parentSession = await (await request.post('/api/family/join', { data: { familyCode, role: 'parent', parentPin: '730862' } })).json() as { familyId: string; token: string }
  const childSession = await (await request.post('/api/family/join', { data: { familyCode, role: 'child' } })).json() as { token: string }
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await page.getByLabel('当前家长 PIN', { exact: true }).fill('730862')
  await page.getByLabel('新家长 PIN', { exact: true }).fill('946208')
  await page.getByLabel('再次输入新 PIN', { exact: true }).fill('946208')
  await page.getByRole('button', { name: '更改家长 PIN', exact: true }).click()
  await expect(page.getByText('家长 PIN 已更改，其他家长设备需要重新登录。孩子设备可以继续阅读。')).toBeVisible()
  const familyUrl = `/api/family/${parentSession.familyId}`
  expect((await request.get(familyUrl, { headers: { Authorization: `Bearer ${parentSession.token}` } })).status()).toBe(401)
  expect((await request.get(familyUrl, { headers: { Authorization: `Bearer ${childSession.token}` } })).status()).toBe(200)
  await page.reload()
  await expect(page.getByRole('heading', { name: '桃阅读 · 家长端', exact: true })).toBeVisible()
  await page.evaluate(() => localStorage.removeItem('taoread-session'))
  await page.goto('/login')
  await page.getByRole('button', { name: '输入家庭码加入', exact: true }).click()
  await page.getByLabel('家庭码', { exact: true }).fill(familyCode)
  await page.getByLabel('家长 PIN', { exact: true }).fill('946208')
  await page.getByRole('button', { name: '进入桃阅读', exact: true }).click()
  await expect(page).toHaveURL(/\/parent/)
  await expect(page.getByRole('heading', { name: '桃阅读 · 家长端', exact: true })).toBeVisible()
})
