"""Rebuild identical glyphs as disjoint, content-hashed WOFF2 unicode subsets.

Requires fonttools[woff] 4.67.0. Original fonts and OFL remain alongside output.
Run from repository root; --check validates coverage and output fingerprints.
"""
import copy
import hashlib
import io
import json
from pathlib import Path
import sys
import subprocess
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / 'apps/web/public/fonts'
OUT = FONTS / 'ui-subsets'
CSS = ROOT / 'apps/web/src/ui-fonts.css'

def digest(data):
    return hashlib.sha256(data).hexdigest()

def ranges(chars):
    runs = []
    start = end = chars[0]
    for cp in chars[1:]:
        if cp == end + 1:
            end = cp
        else:
            runs.append('U+%X' % start if start == end else 'U+%X-%X' % (start, end))
            start = end = cp
    runs.append('U+%X' % start if start == end else 'U+%X-%X' % (start, end))
    return ','.join(runs)

if '--check' in sys.argv:
    manifest = json.loads((OUT / 'manifest.json').read_text())
    for face in manifest:
        original = TTFont(FONTS / face['source'])
        assert digest((FONTS / face['source']).read_bytes()) == face['sourceSha256']
        covered = set()
        for part in face['parts']:
            data = (OUT / part['file']).read_bytes()
            assert digest(data) == part['sha256']
            font = TTFont(io.BytesIO(data))
            chars = set(font.getBestCmap())
            assert chars == set(part['unicodes']) and not covered.intersection(chars)
            # Subsetting must preserve the source advance widths used by pagination.
            for cp, glyph in font.getBestCmap().items():
                assert font['hmtx'][glyph][0] == original['hmtx'][original.getBestCmap()[cp]][0]
            covered.update(chars)
        assert covered == set(original.getBestCmap())
    print('Font coverage, metrics and fingerprints passed')
    sys.exit(0)

inventory = json.loads(subprocess.check_output(['node', str(ROOT / 'scripts/ui-font-glyphs.mjs')], cwd=ROOT))
common = set(inventory['core'])
OUT.mkdir(exist_ok=True)
rules, manifest = [], []
for weight, family, name in [('700 900', 'GenSen Rounded', 'heavy'), ('400 600', 'GenSen Rounded Text', 'regular')]:
    source = FONTS / ('gensen-rounded-' + name + '.woff2')
    original = TTFont(source, recalcTimestamp=False)
    original.ensureDecompiled()
    available = set(original.getBestCmap())
    core = sorted(available & common)
    frequent = [cp for cp in inventory['common'] if cp in available - common][:2048]
    rest = sorted(available - common - set(frequent))
    groups = [core] + [sorted(frequent[i:i + 64]) for i in range(0, len(frequent), 64)] + [rest[i:i + 128] for i in range(0, len(rest), 128)]
    parts = []
    for i, chars in enumerate(groups):
        font = copy.deepcopy(original)
        options = subset.Options()
        options.recalc_timestamp = False
        options.canonical_order = True
        options.notdef_outline = True
        tool = subset.Subsetter(options=options)
        tool.populate(unicodes=chars)
        tool.subset(font)
        target = io.BytesIO()
        font.save(target, reorderTables=True)
        data = target.getvalue()
        filename = name + '-' + str(i) + '-' + digest(data)[:12] + '.woff2'
        (OUT / filename).write_bytes(data)
        parts.append(dict(file=filename, sha256=digest(data), bytes=len(data), unicodes=chars))
        rules.append("@font-face{font-family:'%s';font-style:normal;font-weight:%s;font-display:swap;src:url('/fonts/ui-subsets/%s') format('woff2');unicode-range:%s;}" % (family, weight, filename, ranges(chars)))
    manifest.append(dict(source=source.name, sourceSha256=digest(source.read_bytes()), parts=parts))
CSS.write_text('/* Generated by scripts/subset-ui-fonts.py; original OFL in public/fonts. */\n' + '\n'.join(rules) + '\n', encoding='utf-8')
(OUT / 'manifest.json').write_text(json.dumps(manifest, separators=(',', ':')), encoding='utf-8')
print(json.dumps({f['source']: {'coreBytes': f['parts'][0]['bytes'], 'parts': len(f['parts'])} for f in manifest}))
