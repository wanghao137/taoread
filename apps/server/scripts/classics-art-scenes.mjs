export function checkedClassicScene(bookId, chapter, proposed) {
  const description = scenes[bookId]?.[chapter] || proposed
  // Describe only characters present in this scene. Listing the whole cast
  // makes image models draw all of them, even in a solitary forest chapter.
  const cues = bookId === 'zh-classic-willows' ? {
    鼹鼠: '鼹鼠是黑色毛皮、尖鼻的小鼹鼠。',
    水鼠: '水鼠是棕色的拟人化水鼠。',
    蟾蜍: '蟾蜍是穿衣的绿褐色拟人化蟾蜍。',
    獾: '獾是黑白条纹脸的拟人化獾，不是人。',
  } : bookId === 'zh-classic-oz' ? {
    多萝西: '多萝西是棕色双辫的小女孩，蓝白格子裙、银鞋。',
    托托: '托托是小黑狗。',
    稻草人: '稻草人穿旧衣、戴尖帽，身体由稻草填充。',
    铁皮樵夫: '铁皮樵夫有银色金属身体。',
    胆小狮: '胆小狮是金色雄狮。',
  } : bookId === 'zh-classic-prince' ? {
    小王子: '小王子是金发小男孩，穿朴素绿色衣服；同一画面只出现一个小王子。',
    飞行员: '飞行员是三十岁左右的成年男子，短棕发，成年人的身材与脸，穿朴素飞行服；比金发小男孩高大得多。',
  } : bookId === 'zh-classic-nils' ? {
    尼尔斯: '尼尔斯原本十四岁，浅金发、鼻子有雀斑、穿有补丁的皮裤；变小后仍保持少年外貌和原本衣着，只是全身缩小，不是幼儿。',
  } : {}
  let characters = bookId === 'zh-classic-alice' ? alice : Object.entries(cues).filter(([name]) => description.includes(name)).map(([, cue]) => cue).join('')
  if (bookId === 'zh-classic-nils' && /尼尔斯|男孩|小精灵/.test(description)) {
    characters = [1, 15, 54, 55].includes(chapter)
      ? '尼尔斯是正常身高的十四岁浅金发少年，穿有补丁的皮裤。'
      : 'Scale is essential: Nils is a miniature human only ten centimetres tall. His ENTIRE body is no larger than a goose beak, one eighth of a standing goose height, and one fifteenth of an adult human height. Draw him as a tiny distant figure within the larger scene, never a life-size boy. He has teenage body proportions, light blond hair and patched trousers. 尼尔斯全身缩小，只有十厘米高；不是普通大小的儿童。'
    if (chapter === 1) characters += 'The elf is only five centimetres tall, one thirtieth of the seated boy height; draw it as a tiny figure perched on the trunk rim, not an adult-sized man. '
  }
  return characters ? `${characters}${description}` : description
}
